package com.sotto.app.crypto

import android.annotation.SuppressLint
import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import androidx.security.crypto.EncryptedSharedPreferences
import androidx.security.crypto.MasterKey
import com.sotto.app.domain.repository.KeyPair
import dagger.hilt.android.qualifiers.ApplicationContext
import java.io.File
import java.security.Signature
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Manages cryptographic key material lifecycle.
 *
 * - Identity keys are generated by [CryptoEngine]. Their private halves (and the post-quantum
 *   ones, and staged ones during a rotation) are in a [SecretStore]: files encrypted under a
 *   file key that the Android Keystore wraps, read back as bytes that are wiped after use.
 *   Up to 0.7.3 they were in EncryptedSharedPreferences, which only keeps text: each read
 *   made a String of the key, which can't be wiped. They're moved over on first use
 *   ([migratePrivateKeys]). Public keys stay in EncryptedSharedPreferences.
 * - Double Ratchet session records are in a [SecretStore] too, in a binary form the
 *   RatchetSessionManager encodes into buffers it wipes. Up to 0.7.3 they were JSON text in
 *   EncryptedSharedPreferences; RatchetSessionManager moves each one over when it first
 *   loads it. Initial chain keys are never stored separately: doing so would let anyone
 *   with storage access re-derive every message key.
 * - The SQLCipher database encryption key is stored in EncryptedSharedPreferences
 *   (backed by Android Keystore master key).
 */
// Keys, session state and the database passphrase are written with commit(), not apply():
// they must be on disk before they're used, or a crash right after could lose them
// (ApplySharedPref). Each edit is spelled out rather than restyled through the KTX edit {}
// (UseKtx): this is the identity's store, with no tests on a device to catch a slip.
@SuppressLint("ApplySharedPref", "UseKtx")
@Singleton
class KeyManager @Inject constructor(
    @ApplicationContext private val context: Context,
) {
    private val masterKey = MasterKey.Builder(context)
        .setKeyScheme(MasterKey.KeyScheme.AES256_GCM)
        .build()

    private val encryptedPrefs by lazy {
        EncryptedSharedPreferences.create(
            context,
            PREFS_FILE,
            masterKey,
            EncryptedSharedPreferences.PrefKeyEncryptionScheme.AES256_SIV,
            EncryptedSharedPreferences.PrefValueEncryptionScheme.AES256_GCM,
        ).also { migrateLegacySessionStorage(it) }
    }

    /**
     * Wraps [fileKey]. It never leaves the Android Keystore. It isn't used for the secret files
     * themselves: each decryption through the Keystore leaves copies of the result in buffers
     * we can't wipe (measured on the Note 9), and the result would be a private key.
     */
    private val keystoreKey: SecretKey by lazy {
        val keyStore = java.security.KeyStore.getInstance("AndroidKeyStore").apply { load(null) }
        (keyStore.getKey(PRIVATE_KEY_ALIAS, null) as? SecretKey) ?: KeyGenerator
            .getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore")
            .apply {
                init(
                    KeyGenParameterSpec.Builder(
                        PRIVATE_KEY_ALIAS,
                        KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
                    )
                        .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                        .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                        .setKeySize(256)
                        .build()
                )
            }
            .generateKey()
    }

    /**
     * Our private keys. On first use they're moved here from [encryptedPrefs]. Should that
     * fail, it's tried again at the next start, and meanwhile they're still read from there
     * ([privateKey]), so the app keeps working.
     */
    /** [fileKey], stored wrapped by [keystoreKey]. */
    private val fileKeyStore by lazy {
        SecretStore(File(context.noBackupFilesDir, FILE_KEY_DIR), JcaFileCipher { keystoreKey })
    }

    /**
     * Encrypts the secret files. Unwrapped through the Keystore once per process and kept for
     * its lifetime, so the Keystore's leftover copies are of this key, which opens nothing
     * without the files.
     */
    private val fileKey: ByteArray by lazy {
        fileKeyStore.read(FILE_KEY) ?: run {
            // A new one only when there are no files it would have to open.
            check(privateKeyDir.listFiles().isNullOrEmpty() && sessionDir.listFiles().isNullOrEmpty()) {
                "The key for the secret files is missing"
            }
            ByteArray(32).also {
                java.security.SecureRandom().nextBytes(it)
                fileKeyStore.write(FILE_KEY, it)
            }
        }
    }

    private val privateKeyDir get() = File(context.noBackupFilesDir, PRIVATE_KEY_DIR)
    private val sessionDir get() = File(context.noBackupFilesDir, SESSION_DIR)

    /** Session states, by [sessionFile] name. */
    private val sessions by lazy { SecretStore(sessionDir, RawKeyFileCipher { fileKey }) }

    private val privateKeys: SecretStore by lazy {
        val store = SecretStore(privateKeyDir, RawKeyFileCipher { fileKey })
        try {
            migratePrivateKeys(encryptedPrefs, store, PRIVATE_KEY_NAMES)
        } catch (e: Exception) {
            android.util.Log.e("KeyManager", "Moving the private keys failed, will retry: ${e.message}")
        }
        store
    }

    /** Private key [name], as bytes the caller wipes: from the store, or not yet moved there. */
    private fun privateKey(name: String): ByteArray? =
        privateKeys.read(name) ?: encryptedPrefs.getString(name, null)?.let(::decodeHex)

    private fun hasPrivateKey(name: String): Boolean =
        privateKeys.contains(name) || encryptedPrefs.contains(name)

    /**
     * One-time purge of v1 session storage: static-key ratchet states and the
     * persisted initial chain keys (session_sk_/session_rk_). Those sessions are
     * incompatible with the v2 protocol and the stored chain keys undermine
     * forward secrecy, so they are deleted rather than migrated.
     */
    private fun migrateLegacySessionStorage(prefs: android.content.SharedPreferences) {
        if (prefs.getBoolean(KEY_SESSION_STORAGE_V2, false)) return
        val editor = prefs.edit()
        prefs.all.keys.filter {
            it.startsWith(SEND_KEY_PREFIX) ||
                it.startsWith(RECV_KEY_PREFIX) ||
                it.startsWith(SESSION_PREFIX) ||
                it.startsWith(PQC_PREFIX) ||
                (it.startsWith(RATCHET_PREFIX) && !it.startsWith(RATCHET_PREFIX + "v2_"))
        }.forEach { editor.remove(it) }
        editor.putBoolean(KEY_SESSION_STORAGE_V2, true).commit()
    }

    fun hasIdentity(): Boolean {
        return encryptedPrefs.contains(KEY_USER_ID) &&
            encryptedPrefs.contains(KEY_PUBLIC_SIGNING) &&
            hasPrivateKey(KEY_PRIVATE_SIGNING) &&
            encryptedPrefs.contains(KEY_PUBLIC_IDENTITY) &&
            hasPrivateKey(KEY_PRIVATE_IDENTITY)
    }

    fun storeIdentityKeyPair(keyPair: KeyPair) {
        // Private keys first: the public ones are what says there's an identity (hasIdentity).
        privateKeys.write(KEY_PRIVATE_SIGNING, keyPair.privateSigningKey)
        privateKeys.write(KEY_PRIVATE_IDENTITY, keyPair.privateIdentityKey)
        encryptedPrefs.edit()
            .putString(KEY_PUBLIC_SIGNING, keyPair.publicSigningKey.toHex())
            .putString(KEY_PUBLIC_IDENTITY, keyPair.publicIdentityKey.toHex())
            .commit()
    }

    fun storePqcKeys(encapsulationKey: ByteArray, decapsulationKey: ByteArray) {
        privateKeys.write(KEY_PQC_DECAPSULATION, decapsulationKey)
        encryptedPrefs.edit()
            .putString(KEY_PQC_ENCAPSULATION, encapsulationKey.toHex())
            .commit()
    }

    /** Remove all post-quantum keys (KEM and ML-DSA), e.g. for a classical-only identity. */
    fun clearPqcKeys() {
        encryptedPrefs.edit()
            .remove(KEY_PQC_ENCAPSULATION)
            .remove(KEY_PQC_DECAPSULATION)
            .remove(KEY_MLDSA_PUBLIC)
            .remove(KEY_MLDSA_PRIVATE)
            .commit()
        privateKeys.delete(KEY_PQC_DECAPSULATION, KEY_MLDSA_PRIVATE)
    }

    fun storeMlDsaKeys(publicKey: ByteArray, privateKey: ByteArray) {
        privateKeys.write(KEY_MLDSA_PRIVATE, privateKey)
        encryptedPrefs.edit()
            .putString(KEY_MLDSA_PUBLIC, publicKey.toHex())
            .commit()
    }

    fun getMlDsaPublicKey(): ByteArray? {
        return encryptedPrefs.getString(KEY_MLDSA_PUBLIC, null)?.hexToBytes()
    }

    /**
     * Returns the ML-DSA-65 private signing key. Caller MUST zeroize the returned
     * array after use via `fill(0)` to limit key material lifetime in memory.
     */
    fun getMlDsaPrivateKey(): ByteArray? = privateKey(KEY_MLDSA_PRIVATE)

    fun getPqcEncapsulationKey(): ByteArray? {
        return encryptedPrefs.getString(KEY_PQC_ENCAPSULATION, null)?.hexToBytes()
    }

    /**
     * Returns the PQC decapsulation key. Caller MUST zeroize the returned
     * array after use via `fill(0)` to limit key material lifetime in memory.
     */
    fun getPqcDecapsulationKey(): ByteArray? = privateKey(KEY_PQC_DECAPSULATION)

    /**
     * Runs [block] with our identity key pair and wipes its private keys afterwards, also
     * when [block] throws; null without an identity. [block] must not keep the private
     * keys (copy what must outlive it). Public keys stay readable on a returned pair.
     */
    inline fun <T> withIdentityKeyPair(block: (KeyPair) -> T): T? {
        val keyPair = loadIdentityKeyPair() ?: return null
        try {
            return block(keyPair)
        } finally {
            keyPair.privateIdentityKey.fill(0)
            keyPair.privateSigningKey.fill(0)
        }
    }

    /**
     * The raw pair, private keys included: the caller must wipe them. Use
     * [withIdentityKeyPair] instead; a unit test keeps other code off this.
     */
    fun loadIdentityKeyPair(): KeyPair? {
        val pubSign = encryptedPrefs.getString(KEY_PUBLIC_SIGNING, null)?.hexToBytes() ?: return null
        val pubId = encryptedPrefs.getString(KEY_PUBLIC_IDENTITY, null)?.hexToBytes() ?: return null
        val privSign = privateKey(KEY_PRIVATE_SIGNING) ?: return null
        val privId = privateKey(KEY_PRIVATE_IDENTITY) ?: run {
            privSign.fill(0)
            return null
        }
        return KeyPair(pubSign, privSign, pubId, privId)
    }

    fun storeUserId(userId: String) {
        encryptedPrefs.edit().putString(KEY_USER_ID, userId).apply()
    }

    fun getUserId(): String? {
        return encryptedPrefs.getString(KEY_USER_ID, null)
    }

    fun storeShareCode(shareCode: String) {
        encryptedPrefs.edit().putString(KEY_SHARE_CODE, shareCode).apply()
    }

    fun getShareCode(): String? {
        return encryptedPrefs.getString(KEY_SHARE_CODE, null)
    }

    fun storeCreatedAt(epochMillis: Long) {
        encryptedPrefs.edit().putLong(KEY_CREATED_AT, epochMillis).apply()
    }

    fun getCreatedAt(): Long {
        return encryptedPrefs.getLong(KEY_CREATED_AT, 0L)
    }

    /** The user's own name, sent to new contacts; null removes it. Cleared with the identity by [wipeAll]. */
    fun storeDisplayName(name: String?) {
        encryptedPrefs.edit().apply {
            if (name == null) remove(KEY_DISPLAY_NAME) else putString(KEY_DISPLAY_NAME, name)
        }.apply()
    }

    fun getDisplayName(): String? {
        return encryptedPrefs.getString(KEY_DISPLAY_NAME, null)
    }

    /** Remember whether the current session with [peerId] is hybrid post-quantum (UI indicator). */
    fun setPeerPqcEstablished(peerId: String, pqc: Boolean) {
        encryptedPrefs.edit().putBoolean(PQC_PREFIX + peerId, pqc).apply()
    }

    fun isPeerPqcEstablished(peerId: String): Boolean {
        return encryptedPrefs.getBoolean(PQC_PREFIX + peerId, false)
    }

    fun clearPeerSessionFlags(peerId: String) {
        encryptedPrefs.edit().remove(PQC_PREFIX + peerId).apply()
    }

    fun clearAllPeerSessionFlags() {
        val editor = encryptedPrefs.edit()
        encryptedPrefs.all.keys.filter { it.startsWith(PQC_PREFIX) }.forEach { editor.remove(it) }
        editor.apply()
    }

    /**
     * Highest control-message timestamp accepted from [peerId]. Control messages
     * (session_reset, account_deleted) must be strictly newer, so a replayed
     * control message is rejected.
     */
    fun getLastControlTimestamp(peerId: String): Long {
        return encryptedPrefs.getLong(CTRL_TS_PREFIX + peerId, 0L)
    }

    fun setLastControlTimestamp(peerId: String, timestamp: Long) {
        encryptedPrefs.edit().putLong(CTRL_TS_PREFIX + peerId, timestamp).apply()
    }

    /**
     * Get or create the SQLCipher database encryption key.
     *
     * Android Keystore keys cannot be exported (encoded returns null),
     * so we generate a random key and store it in EncryptedSharedPreferences
     * which is itself protected by an Android Keystore master key.
     */
    @Synchronized
    fun getDatabaseKey(): ByteArray {
        val existing = encryptedPrefs.getString(KEY_DB_PASSPHRASE, null)
        if (existing != null) {
            return existing.hexToBytes()
        }
        val key = ByteArray(32).also { java.security.SecureRandom().nextBytes(it) }
        encryptedPrefs.edit().putString(KEY_DB_PASSPHRASE, key.toHex()).commit()
        return key
    }

    /**
     * Generate a dual-signed auth token:
     * ``<user_id>.<timestamp_ms>.<ed25519_sig>[.<mldsa_sig>]``
     *
     * Centralised here so KtorApiService and WebSocketClient stay in sync.
     */
    fun generateAuthToken(pqcProvider: PqcProvider): String {
        val uid = getUserId() ?: throw IllegalStateException("No identity — bootstrap first")
        // Every token gets its own timestamp, so no two are alike and the relay can
        // refuse one it has already seen (a replay). Two in the same millisecond take
        // the next one.
        val ts = lastTokenMs.updateAndGet { last -> maxOf(System.currentTimeMillis(), last + 1) }.toString()
        val payload = "$uid.$ts"
        val payloadBytes = payload.toByteArray(Charsets.UTF_8)
        val signature = sign(payloadBytes)
        val sigB64 = android.util.Base64.encodeToString(signature, android.util.Base64.NO_WRAP)
        // With ML-DSA keys the relay requires the ML-DSA signature too: a failure
        // throws here rather than sending a token it would only refuse.
        val pqcSig = getMlDsaPrivateKey()?.let { mlDsaPrivKey ->
            try {
                "." + android.util.Base64.encodeToString(
                    pqcProvider.sign(payloadBytes, mlDsaPrivKey), android.util.Base64.NO_WRAP)
            } finally {
                mlDsaPrivKey.fill(0)
            }
        } ?: ""
        return "$payload.$sigB64$pqcSig"
    }

    fun sign(data: ByteArray): ByteArray {
        val privKeyBytes = privateKey(KEY_PRIVATE_SIGNING)
            ?: throw IllegalStateException("No signing key available")
        try {
            // Straight on the key bytes, leaving no copies of the private key (RawKeyCrypto.kt).
            rawEd25519Sign(privKeyBytes, data)?.let { return it }
            val kf = java.security.KeyFactory.getInstance("Ed25519", "BC")
            val privKey = kf.generatePrivate(java.security.spec.PKCS8EncodedKeySpec(privKeyBytes))
            val sig = Signature.getInstance("Ed25519", "BC")
            sig.initSign(privKey)
            sig.update(data)
            return sig.sign()
        } finally {
            privKeyBytes.fill(0)
        }
    }

    /**
     * Saves the session state [state] (RatchetSessionManager's encoding) as [sessionId]; the
     * caller wipes [state]. Written synchronously: a state lost after a crash rolls the chain
     * back and makes us reuse message keys, which the peer then drops as duplicates.
     * Returns false if the write failed.
     */
    fun saveSessionState(sessionId: String, state: ByteArray): Boolean = try {
        sessions.write(sessionFile(sessionId), state)
        true
    } catch (e: Exception) {
        android.util.Log.e("KeyManager", "Saving a session state failed: ${e.message}")
        false
    }

    /** The session state saved as [sessionId], as bytes the caller wipes; null if there is none. */
    fun loadSessionState(sessionId: String): ByteArray? = sessions.read(sessionFile(sessionId))

    fun removeSessionState(sessionId: String) {
        sessions.delete(sessionFile(sessionId))
        removeLegacySessionState(sessionId)
    }

    fun removeAllSessionStates() {
        sessions.deleteAll()
        val editor = encryptedPrefs.edit()
        encryptedPrefs.all.keys
            .filter { it.startsWith(RATCHET_PREFIX) }
            .forEach { editor.remove(it) }
        editor.commit()
    }

    /** A session state as stored up to 0.7.3 (JSON text), for RatchetSessionManager to move over. */
    fun loadLegacySessionState(sessionId: String): String? = encryptedPrefs.getString(RATCHET_PREFIX + sessionId, null)

    fun removeLegacySessionState(sessionId: String) {
        if (encryptedPrefs.contains(RATCHET_PREFIX + sessionId)) {
            encryptedPrefs.edit().remove(RATCHET_PREFIX + sessionId).commit()
        }
    }

    /** A file name for [sessionId] (peer ids come from the relay: never used as a path as they are). */
    private fun sessionFile(sessionId: String): String =
        sessionId.toByteArray(Charsets.UTF_8).joinToString("") { "%02x".format(it) }

    // ── Staged key rotation (crash-safe) ──────────────────────────────

    /**
     * Stage new identity keys before the server call.
     * If the server accepts, call [promoteStagedKeys] to make them active.
     * If the server rejects or the call fails, call [clearStagedKeys].
     */
    fun stageIdentityKeyPair(keyPair: KeyPair) {
        // Private keys first: the staged public signing key is what says keys are staged.
        privateKeys.write(PENDING_PRIVATE_SIGNING, keyPair.privateSigningKey)
        privateKeys.write(PENDING_PRIVATE_IDENTITY, keyPair.privateIdentityKey)
        encryptedPrefs.edit()
            .putString(PENDING_PUBLIC_SIGNING, keyPair.publicSigningKey.toHex())
            .putString(PENDING_PUBLIC_IDENTITY, keyPair.publicIdentityKey.toHex())
            .commit()
    }

    fun stagePqcKeys(encapsulationKey: ByteArray, decapsulationKey: ByteArray) {
        privateKeys.write(PENDING_PQC_DECAPSULATION, decapsulationKey)
        encryptedPrefs.edit()
            .putString(PENDING_PQC_ENCAPSULATION, encapsulationKey.toHex())
            .commit()
    }

    fun stageMlDsaKeys(publicKey: ByteArray, privateKey: ByteArray) {
        privateKeys.write(PENDING_MLDSA_PRIVATE, privateKey)
        encryptedPrefs.edit()
            .putString(PENDING_MLDSA_PUBLIC, publicKey.toHex())
            .commit()
    }

    /**
     * Promote staged keys to active. Called after server confirms rotation,
     * or on app startup if staged keys exist (server accepted but app crashed
     * before promotion).
     */
    fun promoteStagedKeys() {
        val pubSign = encryptedPrefs.getString(PENDING_PUBLIC_SIGNING, null) ?: return
        val pubId = encryptedPrefs.getString(PENDING_PUBLIC_IDENTITY, null) ?: return
        val pqcEk = encryptedPrefs.getString(PENDING_PQC_ENCAPSULATION, null)
        val mlDsaPub = encryptedPrefs.getString(PENDING_MLDSA_PUBLIC, null)
        val privSign = privateKey(PENDING_PRIVATE_SIGNING) ?: return
        val privId = privateKey(PENDING_PRIVATE_IDENTITY)
        val pqcDk = pqcEk?.let { privateKey(PENDING_PQC_DECAPSULATION) }
        val mlDsaPriv = mlDsaPub?.let { privateKey(PENDING_MLDSA_PRIVATE) }
        try {
            if (privId == null) return
            // 1. The new private keys take the place of the old ones. Should this stop
            //    halfway, the staged keys and the server's confirmation are still recorded,
            //    and startup promotes them again before anything uses the keys.
            privateKeys.write(KEY_PRIVATE_SIGNING, privSign)
            privateKeys.write(KEY_PRIVATE_IDENTITY, privId)
            if (pqcEk != null && pqcDk != null) privateKeys.write(KEY_PQC_DECAPSULATION, pqcDk)
            if (mlDsaPub != null && mlDsaPriv != null) privateKeys.write(KEY_MLDSA_PRIVATE, mlDsaPriv)

            // 2. The public keys, and the end of the staging, in one synchronous commit.
            val editor = encryptedPrefs.edit()
                .putString(KEY_PUBLIC_SIGNING, pubSign)
                .putString(KEY_PUBLIC_IDENTITY, pubId)
            if (pqcEk != null && pqcDk != null) editor.putString(KEY_PQC_ENCAPSULATION, pqcEk)
            if (mlDsaPub != null && mlDsaPriv != null) editor.putString(KEY_MLDSA_PUBLIC, mlDsaPub)
            editor
                .remove(PENDING_PUBLIC_SIGNING)
                .remove(PENDING_PRIVATE_SIGNING)
                .remove(PENDING_PUBLIC_IDENTITY)
                .remove(PENDING_PRIVATE_IDENTITY)
                .remove(PENDING_PQC_ENCAPSULATION)
                .remove(PENDING_PQC_DECAPSULATION)
                .remove(PENDING_MLDSA_PUBLIC)
                .remove(PENDING_MLDSA_PRIVATE)
                .remove(PENDING_SERVER_CONFIRMED)
                .commit()

            // 3. The staged private keys aren't needed any more.
            privateKeys.delete(*PENDING_PRIVATE_KEYS)
        } finally {
            privSign.fill(0)
            privId?.fill(0)
            pqcDk?.fill(0)
            mlDsaPriv?.fill(0)
        }
    }

    /** Public signing key of the staged (not yet promoted) key set, if any. */
    fun getStagedPublicSigningKey(): ByteArray? =
        encryptedPrefs.getString(PENDING_PUBLIC_SIGNING, null)?.hexToBytes()

    fun hasStagedKeys(): Boolean {
        return encryptedPrefs.contains(PENDING_PUBLIC_SIGNING)
    }

    /**
     * Mark that the server has confirmed the staged key rotation.
     * Must be called after the server accepts the new keys and before
     * [promoteStagedKeys]. Uses commit() so the flag survives a crash
     * between server confirmation and local promotion.
     */
    fun markRotationConfirmedByServer() {
        encryptedPrefs.edit()
            .putBoolean(PENDING_SERVER_CONFIRMED, true)
            .commit()
    }

    fun isRotationConfirmedByServer(): Boolean {
        return encryptedPrefs.getBoolean(PENDING_SERVER_CONFIRMED, false)
    }

    fun clearStagedKeys() {
        // Use commit() (synchronous) instead of apply() to ensure staged keys
        // are removed before returning. With apply(), a crash before the async
        // disk write completes would leave staged keys on disk, causing
        // recoverFromInterruptedKeyRotation() to promote rejected keys.
        encryptedPrefs.edit()
            .remove(PENDING_PUBLIC_SIGNING)
            .remove(PENDING_PRIVATE_SIGNING)
            .remove(PENDING_PUBLIC_IDENTITY)
            .remove(PENDING_PRIVATE_IDENTITY)
            .remove(PENDING_PQC_ENCAPSULATION)
            .remove(PENDING_PQC_DECAPSULATION)
            .remove(PENDING_MLDSA_PUBLIC)
            .remove(PENDING_MLDSA_PRIVATE)
            .remove(PENDING_SERVER_CONFIRMED)
            .commit()
        privateKeys.delete(*PENDING_PRIVATE_KEYS)
    }

    fun wipeAll() {
        encryptedPrefs.edit().clear().putBoolean(KEY_SESSION_STORAGE_V2, true).commit()
        privateKeys.deleteAll()
        sessions.deleteAll()
        fileKeyStore.deleteAll()
    }

    companion object {
