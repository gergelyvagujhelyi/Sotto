        private const val SESSION_PREFIX = "session_id_"
        private const val SEND_KEY_PREFIX = "session_sk_"
        private const val RECV_KEY_PREFIX = "session_rk_"
        private const val RATCHET_PREFIX = "ratchet_"
        private const val CTRL_TS_PREFIX = "ctrl_ts_"
        private const val KEY_SESSION_STORAGE_V2 = "session_storage_v2"
        private const val PENDING_PUBLIC_SIGNING = "pending_pub_sign"
        private const val PENDING_PRIVATE_SIGNING = "pending_priv_sign"
        private const val PENDING_PUBLIC_IDENTITY = "pending_pub_id"
        private const val PENDING_PRIVATE_IDENTITY = "pending_priv_id"
        private const val PENDING_PQC_ENCAPSULATION = "pending_pqc_ek"
        private const val PENDING_PQC_DECAPSULATION = "pending_pqc_dk"
        private const val PENDING_MLDSA_PUBLIC = "pending_mldsa_pub"
        private const val PENDING_MLDSA_PRIVATE = "pending_mldsa_priv"
        private const val PENDING_SERVER_CONFIRMED = "pending_server_confirmed"

        /** Where the [SecretStore]s keep their files (in noBackupFilesDir), and the Keystore key. */
        private const val PRIVATE_KEY_DIR = "private_keys"
        private const val SESSION_DIR = "sessions"
        private const val FILE_KEY_DIR = "private_keys_file_key"
        private const val FILE_KEY = "file_key"
