/**
 * The owner's relay: the only one with this app's Firebase key (push), the one whose invite
 * links open the app (Android App Links), and the one whose certificate chain is pinned. It's
 * kept out of the repository: set `sotto.ownerRelayHost=relay.example.com` in `local.properties`
 * or `~/.gradle/gradle.properties` (or pass `-Psotto.ownerRelayHost=…`), or SOTTO_OWNER_RELAY_HOST
 * in the environment, as CI does from a secret. Without it the app has no owner relay: no push,
 * and invite links open through the relay's invite page.
 */
val ownerRelayHost: String = run {
    val local = Properties().apply {
        rootProject.file("local.properties").takeIf { it.exists() }?.inputStream()?.use { load(it) }
    }
    (providers.gradleProperty("sotto.ownerRelayHost").orNull
        ?: local.getProperty("sotto.ownerRelayHost")
        ?: providers.environmentVariable("SOTTO_OWNER_RELAY_HOST").orNull
        ?: "").trim()
}
val ownerRelayUrl = if (ownerRelayHost.isEmpty()) "" else "https://$ownerRelayHost"

/**
 * The network security config: the owner's relay pinned to Let's Encrypt's root keys, and in
 * debug builds plain HTTP to local development hosts. Generated, so the relay's host stays out
 * of the repository.
 */
abstract class NetworkSecurityConfigTask : DefaultTask() {
    @get:Input abstract val relayHost: Property<String>
    @get:Input abstract val debugHosts: Property<Boolean>
    @get:OutputDirectory abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun write() {
        val host = relayHost.get()
        val pinned = if (host.isEmpty()) "" else """
    <!-- Certificate pinning for the owner's relay. The pins are Let's Encrypt's root keys, not
         the server's own certificate: the server gets a new key on every renewal and Let's
         Encrypt rotates its intermediates, but these roots last until 2035-2040. Every chain
         Android can build for the server's certificate ends at one of them. Compute a pin from a
         root certificate with:
           openssl x509 -in root.pem -pubkey -noout \
             | openssl pkey -pubin -outform der \
             | openssl dgst -sha256 -binary | openssl enc -base64
    -->
    <domain-config>
        <domain includeSubdomains="true">$host</domain>
        <pin-set expiration="2028-10-01">
            <!-- ISRG Root X1 (until 2035), which every supported Android version trusts -->
            <pin digest="SHA-256">C5+lpZ7tcVwmwQIMcRtPbsQtWLABXhQzejna0wHFr8M=</pin>
            <!-- ISRG Root X2 (until 2040) -->
            <pin digest="SHA-256">diGVwiVYbubAI3RW4hB9xU8e/CH2GnkuvVFZE8zmgzI=</pin>
            <!-- ISRG Root YE, the root above the current ECDSA intermediates (YE1, YE2) -->
            <pin digest="SHA-256">sCkq5UWXjg+7mKu9lMhhYF5bGLsy7VI/UNW3tccdR7w=</pin>
        </pin-set>
    </domain-config>
"""
        val local = if (!debugHosts.get()) "" else """
    <!-- Debug only: plain HTTP for local development (the emulator's host, a LAN name, and a
         phone reaching a relay on the computer through `adb reverse tcp:8000 tcp:8000`). -->
    <domain-config cleartextTrafficPermitted="true">
        <domain includeSubdomains="true">sotto.local</domain>
        <domain includeSubdomains="true">10.0.2.2</domain>
        <domain>localhost</domain>
    </domain-config>
"""
        val file = outputDirectory.file("xml/network_security_config.xml").get().asFile
        file.parentFile.mkdirs()
        file.writeText(
            """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by app/build.gradle.kts (NetworkSecurityConfigTask); don't edit. -->
<network-security-config>$pinned$local
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>
</network-security-config>
""",
        )
    }
}

val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) {
        load(keystorePropertiesFile.inputStream())
    }
}

android {
    namespace = "com.sotto.app"
    compileSdk = 35

    signingConfigs {
        create("release") {
            if (keystorePropertiesFile.exists()) {
                storeFile = file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }

    defaultConfig {
        applicationId = "com.vagujhelyigergely.sotto"
        // The owner's relay: the only one with this app's Firebase key, so the only one
        // that can push. Not a default: setup gets the relay from an invite or the user.
        buildConfigField("String", "OWNER_RELAY_URL", "\"$ownerRelayUrl\"")
        // Its invite links (https://<relay>/invite#…) open the app: Android App Links, verified
        // by the relay's /.well-known/assetlinks.json (ADR-24). Without an owner relay the filter
        // names a host that can't exist (.invalid is reserved), so it never matches.
        manifestPlaceholders["inviteHost"] = ownerRelayHost.ifEmpty { "relay.invalid" }
        minSdk = 26
        targetSdk = 35
        versionCode = 70
        versionName = "0.7.28"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"

        javaCompileOptions {
            annotationProcessorOptions {
                arguments["room.schemaLocation"] = "$projectDir/schemas"
            }
        }

        ksp {
            arg("room.schemaLocation", "$projectDir/schemas")
        }
    }

    buildTypes {
        debug {
            isDebuggable = true
            // Emulator: 10.0.2.2 routes to host machine's localhost
            buildConfigField("String", "DEFAULT_RELAY_URL", "\"http://10.0.2.2:8000\"")
            buildConfigField("String", "LEGACY_RELAY_URL", "\"http://10.0.2.2:8000\"")
        }
        release {
            signingConfig = signingConfigs.getByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro"
            )
            // No relay until setup gets one (an invite, or an address the user types).
            buildConfigField("String", "DEFAULT_RELAY_URL", "\"\"")
            // Accounts made before the relay was a setting live on the owner's relay.
            buildConfigField("String", "LEGACY_RELAY_URL", "\"$ownerRelayUrl\"")
            // ARM phones only: native code (WebRTC, SQLCipher) for x86/x86_64, which only
            // emulators and rare Intel devices use, more than doubled the APK (73 MB to 34 MB).
            // Debug builds keep every ABI for emulators.
            ndk { abiFilters += listOf("arm64-v8a", "armeabi-v7a") }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    androidResources {
        // The per-app language list (Android 13+ Settings > Apps > Sotto > Language), built
        // from res/values (English, see res/resources.properties) and each values-<lang>.
        generateLocaleConfig = true
        // Only the languages Sotto has: libraries bring their own translations (dialog buttons,
        // accessibility labels), which would show a third language beside Sotto's English.
        localeFilters += listOf("en", "hu")
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += "META-INF/versions/9/OSGI-INF/MANIFEST.MF"
        }
    }
}

// Each variant gets its own generated network security config (see NetworkSecurityConfigTask).
androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val task = tasks.register<NetworkSecurityConfigTask>("generate${name}NetworkSecurityConfig") {
            relayHost.set(ownerRelayHost)
            debugHosts.set(variant.buildType == "debug")
        }
        variant.sources.res?.addGeneratedSourceDirectory(task, NetworkSecurityConfigTask::outputDirectory)
    }
}

